#!/usr/bin/env python3
"""Build the system map from the repository.

    python3 docs/System/map/build.py            # regenerate docs/System/map.md and docs/System/map/
    python3 docs/System/map/build.py --check    # exit 1 if the committed map is stale or incomplete
    python3 docs/System/map/build.py --artifact page.html   # also write the page body, to publish it

Outputs (never edit them by hand): docs/System/map.md (GitHub, editors), docs/System/map/index.html
(the full page: open it in a browser), and one standalone SVG per figure in docs/System/map/svg/.

What the map says lives in three project files:
  facts.py     reads the facts from the code, and reports what the drawings do not cover yet
  figures.py   the drawings, and figures.coverage(): what the code has that a drawing lacks
  sections.py  the page: title, lede, legend, and each section's text, tables and figures

The check fails when (1) the committed outputs are not what the code generates today, or (2) facts
or figures report a problem: something new the drawings do not show, or a claim the code now
contradicts. Each problem names the file to edit.

Output depends only on files git tracks or would track, so two builds of the same commit are
identical. Standard library only. Seeded by the `system-map` skill of ClaudeCodeTemplate.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.dont_write_bytecode = True  # no __pycache__ next to the docs

import facts  # noqa: E402
import figures  # noqa: E402
import page  # noqa: E402
import sections  # noqa: E402
import svgkit  # noqa: E402

MD_OUT = "docs/System/map.md"
HTML_OUT = "docs/System/map/index.html"
SVG_DIR = "docs/System/map/svg"


def build(root: Path):
    svgkit.WARN.clear()
    F, problems = facts.collect(root)
    problems = list(problems) + list(figures.coverage(F))
    secs = sections.build_sections(F)
    problems += [f"Text overflow (edit the figure in figures.py): {w}" for w in svgkit.WARN]

    slugs = [b[1].slug for _, _, blocks in secs for b in blocks if b[0] == "fig"]
    for s in sorted({s for s in slugs if slugs.count(s) > 1}):
        problems.append(f"Two figures share the slug {s!r}: rename one in figures.py.")

    title = sections.TITLE
    lede = sections.lede(F)
    nav = "".join(f'<a href="#{svgkit.esc(a)}">{t}</a>' for a, t, _ in secs)
    head = f"<title>{svgkit.esc(title)}</title>\n<style>{page.PAGE_CSS}</style>"
    body = (f'<header class="top"><div class="wrap"><h1>{svgkit.esc(title)}</h1><p class="lede">{lede}</p>'
            f"{page.legend_html(sections.LEGEND)}</div></header>\n"
            f'<nav aria-label="Sections"><div class="wrap">{nav}</div></nav>\n'
            f"<main>\n{page.render_html(secs)}\n</main>\n")

    md = (f"<!-- Generated by docs/System/map/build.py. Do not edit: change facts.py, figures.py or "
          f"sections.py and run `python3 docs/System/map/build.py`. -->\n\n# {title}\n\n{lede}\n\n"
          f"The full page, with dark mode and an index, is [map/index.html](map/index.html): open it in a "
          f"browser. Legend: {page.legend_md(sections.LEGEND)}\n\n" + page.render_md(secs))

    outputs = {
        MD_OUT: md,
        HTML_OUT: (f'<!doctype html>\n<html lang="{sections.LANG}">\n<head>\n<meta charset="utf-8">\n'
                   f'<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
                   f"{head}\n</head>\n<body>\n{body}</body>\n</html>\n"),
    }
    for _, _, blocks in secs:
        for b in blocks:
            if b[0] == "fig":
                outputs[f"{SVG_DIR}/{b[1].slug}.svg"] = b[1].standalone(page.SVG_CSS)
    return outputs, problems, head + "\n" + body


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the system map.")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the map is stale or incomplete")
    ap.add_argument("--root", type=Path, default=HERE.parents[2], help="repository root (default: this repo)")
    ap.add_argument("--artifact", type=Path, help="also write the page head + body to this file")
    args = ap.parse_args()
    root = args.root.resolve()

    outputs, problems, artifact_body = build(root)
    if problems:
        print("The system map needs a hand edit:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    svg_dir = root / SVG_DIR
    stale = sorted(p.relative_to(root).as_posix() for p in svg_dir.glob("*.svg")
                   if p.relative_to(root).as_posix() not in outputs) if svg_dir.is_dir() else []
    changed = [rel for rel, text in outputs.items()
               if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text]

    if args.check:
        if changed or stale:
            print("The system map is stale. Run: python3 docs/System/map/build.py", file=sys.stderr)
            for rel in changed:
                print(f"  - changes {rel}", file=sys.stderr)
            for rel in stale:
                print(f"  - removes {rel}", file=sys.stderr)
            return 1
        print(f"Map current ({len(outputs)} files).")
        return 0

    for rel in changed:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(outputs[rel], encoding="utf-8")
    for rel in stale:
        (root / rel).unlink()
    if args.artifact:
        args.artifact.write_text(artifact_body, encoding="utf-8")
    if changed or stale:
        print("Map updated: " + ", ".join(changed + [f"{s} (removed)" for s in stale]))
    else:
        print("Map unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
